ROLLBACK;
END CATCH
END

IF @END_TASK = 1
BEGIN
BEGIN TRY
UPDATE TASKS
SET
END_DATE_TIME = CONVERT(NVARCHAR(19), GETDATE(), 120),
ACTUAL_TIME_TASK_TOOK = (SELECT TOP 1 DATEDIFF(
    SECOND,
    CONVERT(DATETIME, START_DATE_TIME),
    CONVERT(DATETIME, CONVERT(NVARCHAR(19), GETDATE(), 120))
) AS HoursDifference FROM TASKS WHERE TASKS_ID = @TASK_ID_ACCPETED) / 3600.0
WHERE TASKS_ID = @TASK_ID_ACCPETED

