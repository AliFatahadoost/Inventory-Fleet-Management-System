-- 5. CREATE_UPDATE_DELETE_DRIVER
CREATE PROCEDURE dbo.CREATE_UPDATE_DELETE_DRIVER
    @ACTION                NVARCHAR(50),
    @DRIVER_ID             NUMERIC      = NULL,
    @DRIVER_NAME           NVARCHAR(50) = NULL,
    @DRIVER_LAST_NAME      NVARCHAR(50) = NULL,
    @DRIVERS_NATIONAL_CODE NVARCHAR(50) = NULL,
    @DRIVERS_PHONE_NUMBER  NVARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET @ACTION = UPPER(@ACTION);

    IF @ACTION = N'CREATE_DRIVER'
       AND @DRIVER_NAME IS NOT NULL
       AND @DRIVER_LAST_NAME IS NOT NULL
       AND @DRIVERS_NATIONAL_CODE IS NOT NULL
       AND @DRIVERS_PHONE_NUMBER IS NOT NULL
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM dbo.DRIVERS WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE)
            INSERT INTO dbo.DRIVERS (DRIVER_NAME, DRIVER_LAST_NAME, DRIVERS_NATIONAL_CODE, DRIVERS_PHONE_NUMBER)
            VALUES (@DRIVER_NAME, @DRIVER_LAST_NAME, @DRIVERS_NATIONAL_CODE, @DRIVERS_PHONE_NUMBER);
        ELSE
            UPDATE dbo.DRIVERS
            SET IS_DELETED = 0,
                DRIVER_NAME = @DRIVER_NAME,
                DRIVER_LAST_NAME = @DRIVER_LAST_NAME,
                DRIVERS_PHONE_NUMBER = @DRIVERS_PHONE_NUMBER
            WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE;
    END

    IF @ACTION = N'UPDATE_DRIVER' AND @DRIVER_ID IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM dbo.DRIVERS WHERE DRIVER_ID = @DRIVER_ID)
            UPDATE dbo.DRIVERS
            SET DRIVER_NAME           = ISNULL(@DRIVER_NAME, DRIVER_NAME),
                DRIVER_LAST_NAME      = ISNULL(@DRIVER_LAST_NAME, DRIVER_LAST_NAME),
                DRIVERS_NATIONAL_CODE = ISNULL(@DRIVERS_NATIONAL_CODE, DRIVERS_NATIONAL_CODE),
                DRIVERS_PHONE_NUMBER  = ISNULL(@DRIVERS_PHONE_NUMBER, DRIVERS_PHONE_NUMBER)
            WHERE DRIVER_ID = @DRIVER_ID;
    END

    IF @ACTION = N'DELETE_DRIVER' AND @DRIVER_ID IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM dbo.DRIVERS WHERE DRIVER_ID = @DRIVER_ID)
            UPDATE dbo.DRIVERS SET IS_DELETED = 1 WHERE DRIVER_ID = @DRIVER_ID;
    END
    SELECT 1
END
GO

-- 6. CREATE_UPDATE_DELETE_INVENTORY_LOCATION
CREATE PROCEDURE dbo.CREATE_UPDATE_DELETE_INVENTORY_LOCATION
    @ACTION                        NVARCHAR(50),
    @INVENTORY_LOCATION_ID         NUMERIC      = NULL,
    @INVENTORY_LOCATION_NAME       NVARCHAR(50) = NULL,
    @INVENTORY_LOCATION_ADDRESS    NVARCHAR(300) = NULL,
    @INVENTORY_LOCATION_LAT        DECIMAL(9, 6) = NULL,
    @INVENTORY_LOCATION_LONG       DECIMAL(9, 6) = NULL,
    @LT_INVENTORY_LOCATION_TYPE_ID NUMERIC      = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET @ACTION = UPPER(@ACTION);

    IF @ACTION = N'CREATE_INVENTORY_LOCATION'
       AND @INVENTORY_LOCATION_NAME IS NOT NULL
       AND @INVENTORY_LOCATION_ADDRESS IS NOT NULL
       AND @INVENTORY_LOCATION_LAT IS NOT NULL
       AND @INVENTORY_LOCATION_LONG IS NOT NULL
       AND @LT_INVENTORY_LOCATION_TYPE_ID IS NOT NULL
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM dbo.INVENTORY_LOCATION
                       WHERE INVENTORY_LOCATION_NAME = @INVENTORY_LOCATION_NAME
                         AND INVENTORY_LOCATION_ADDRESS = @INVENTORY_LOCATION_ADDRESS
                         AND INVENTORY_LOCATION_LAT = @INVENTORY_LOCATION_LAT
                         AND INVENTORY_LOCATION_LONG = @INVENTORY_LOCATION_LONG)
            INSERT INTO dbo.INVENTORY_LOCATION
                (INVENTORY_LOCATION_NAME, INVENTORY_LOCATION_ADDRESS,
                 INVENTORY_LOCATION_LAT, INVENTORY_LOCATION_LONG,
                 LT_INVENTORY_LOCATION_TYPE_ID)
            VALUES
                (@INVENTORY_LOCATION_NAME, @INVENTORY_LOCATION_ADDRESS,
                 @INVENTORY_LOCATION_LAT, @INVENTORY_LOCATION_LONG,
                 @LT_INVENTORY_LOCATION_TYPE_ID);
        ELSE
            UPDATE dbo.INVENTORY_LOCATION
            SET IS_DELETED = 0,
                INVENTORY_LOCATION_NAME = @INVENTORY_LOCATION_NAME,
                INVENTORY_LOCATION_ADDRESS = @INVENTORY_LOCATION_ADDRESS,
