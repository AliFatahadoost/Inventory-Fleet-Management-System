-- GET_USER_ID_BY_SESSION
CREATE FUNCTION dbo.GET_USER_ID_BY_SESSION (@LOGIN_SESSION NVARCHAR(512))
RETURNS NUMERIC
AS
BEGIN
    DECLARE @RESULT NUMERIC = (SELECT TOP 1 SYS_USER_ID FROM dbo.SYS_USERS WHERE LOGIN_SESSION = @LOGIN_SESSION)
    RETURN @RESULT
END
GO

-- LOGIN_LOG_SELECT
CREATE FUNCTION dbo.LOGIN_LOG_SELECT (@TOKEN NVARCHAR(512))
RETURNS TABLE
AS
RETURN
(
    SELECT
        USER_LOGIN_LOG_ID,
        USERNAME,
        LOGIN_DATE
    FROM dbo.USER_LOGIN_LOG ULL
    INNER JOIN dbo.SYS_USERS SU ON ULL.SYS_USER_ID = SU.SYS_USER_ID
    WHERE SU.LOGIN_SESSION = @TOKEN
)
GO

-- ROLES_LOG_SELECT
CREATE FUNCTION dbo.ROLES_LOG_SELECT (@TOKEN NVARCHAR(512))
RETURNS TABLE
AS
RETURN
(
    SELECT
        UR.USERS_ROLES_ID,
        LR.ROLES_TITLE,
        UR.ASSIGNMENT_DATE
    FROM dbo.USERS_ROLES UR
    INNER JOIN dbo.SYS_USERS SU ON UR.SYS_USER_ID = SU.SYS_USER_ID
    INNER JOIN dbo.LT_ROLES LR ON UR.ROLE_CODE = LR.ROLE_CODE
    WHERE SU.LOGIN_SESSION = @TOKEN AND UR.IS_ACTIVE = 1
)
GO

