-- 20. TASKS_REPORT
CREATE PROCEDURE dbo.TASKS_REPORT
    @BY_USER_SESSION NVARCHAR(512) = NULL,
    @TASK_ID_ACCPETED NUMERIC = NULL,
    @END_TASK BIT = NULL
AS
BEGIN
    BEGIN TRANSACTION
    IF @TASK_ID_ACCPETED IS NOT NULL AND @BY_USER_SESSION IS NOT NULL AND EXISTS(SELECT 1 FROM dbo.TASKS WHERE TASKS_ID = @TASK_ID_ACCPETED) AND NOT @END_TASK = 1
    BEGIN
        BEGIN TRY
            UPDATE dbo.TASKS
            SET ACCEPTED_BY_SYS_USER_ID = dbo.GET_USER_ID_BY_SESSION(@BY_USER_SESSION),
                START_DATE_TIME = CONVERT(NVARCHAR(19), GETDATE(), 120)
            WHERE TASKS_ID = @TASK_ID_ACCPETED
        END TRY
        BEGIN CATCH
            ROLLBACK;
        END CATCH
    END

    IF @END_TASK = 1
    BEGIN
        BEGIN TRY
            UPDATE dbo.TASKS
            SET END_DATE_TIME = CONVERT(NVARCHAR(19), GETDATE(), 120),
                ACTUAL_TIME_TASK_TOOK = (SELECT TOP 1 DATEDIFF(SECOND, CONVERT(DATETIME, START_DATE_TIME), CONVERT(DATETIME, CONVERT(NVARCHAR(19), GETDATE(), 120))) / 3600.0
                                         FROM dbo.TASKS WHERE TASKS_ID = @TASK_ID_ACCPETED)
            WHERE TASKS_ID = @TASK_ID_ACCPETED

            INSERT INTO dbo.WORK_HOUR_REPORT_LOG (SYS_USER_ID, COMPLETED_TASK_ID)
            VALUES ((SELECT TOP 1 SYS_USER_ID FROM dbo.SYS_USERS WHERE LOGIN_SESSION = @BY_USER_SESSION), @TASK_ID_ACCPETED)
        END TRY
        BEGIN CATCH
            ROLLBACK;
        END CATCH
    END

    SELECT
        TASKS_ID,
        TASK_NAME,
        TASK_DESCRIPTION,
        CASE WHEN START_DATE_TIME IS NULL THEN N'No one has accepted this task yet' ELSE START_DATE_TIME END AS START_DATE_TIME,
        CASE WHEN START_DATE_TIME IS NULL THEN N'No one has finished this task yet' ELSE END_DATE_TIME END AS END_DATE_TIME,
        EST_HOURS_IT_WILL_TAKE,
        HOURLY_RATE_FOR_TASK,
        SU.USERNAME AS TASK_CREATED_BY
    FROM dbo.TASKS T
    INNER JOIN dbo.SYS_USERS SU ON SU.SYS_USER_ID = T.TASK_CREATED_BY_SYS_USER_ID
    COMMIT
END
GO

