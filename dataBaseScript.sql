		BEGIN
			IF EXISTS(SELECT 1 FROM LT_INVENTORY_LOCATION_TYPE WHERE INVENTORY_LOCATION_TYPE_TITLE LIKE @INVENTORY_LOCATION_TITLE)
			UPDATE LT_INVENTORY_LOCATION_TYPE SET INVENTORY_LOCATION_TYPE_TITLE = @NEW_INVENTORY_LOCATION_TITLE WHERE INVENTORY_LOCATION_TYPE_TITLE LIKE @INVENTORY_LOCATION_TITLE
		END
		
		IF LOWER(@ACTION) = LOWER(N'DELETE_INVENTORY_TYPE') AND @INVENTORY_LOCATION_TITLE IS NOT NULL
		BEGIN
			IF EXISTS(SELECT 1 FROM LT_INVENTORY_LOCATION_TYPE WHERE INVENTORY_LOCATION_TYPE_TITLE LIKE @INVENTORY_LOCATION_TITLE)
			UPDATE LT_INVENTORY_LOCATION_TYPE SET IS_DELETED = 1 WHERE INVENTORY_LOCATION_TYPE_TITLE LIKE @INVENTORY_LOCATION_TITLE
		END
		
		IF LOWER(@ACTION) = LOWER(N'ADD_PRODUCTS_CATEGORY') AND @PRODUCTS_CATEGORY_NAME IS NOT NULL 
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM PRODUCTS_CATEGORY WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME)
			INSERT INTO PRODUCTS_CATEGORY (PRODUCTS_CATEGORY_NAME) VALUES (@PRODUCTS_CATEGORY_NAME)
			ELSE
			UPDATE PRODUCTS_CATEGORY SET IS_DELETED = 0 WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME
		END
		
		IF LOWER(@ACTION) = LOWER(N'MODIFY_PRODUCTS_CATEGORY') AND @PRODUCTS_CATEGORY_NAME IS NOT NULL 
		BEGIN
			IF EXISTS (SELECT 1 FROM PRODUCTS_CATEGORY WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME)
			UPDATE PRODUCTS_CATEGORY SET PRODUCTS_CATEGORY_NAME = @NEW_PRODUCTS_CATEGORY_NAME WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME
		END
		
		IF LOWER(@ACTION) = LOWER(N'DELETE_PRODUCTS_CATEGORY') AND @PRODUCTS_CATEGORY_NAME IS NOT NULL 
		BEGIN
			IF EXISTS (SELECT 1 FROM PRODUCTS_CATEGORY WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME)
			UPDATE PRODUCTS_CATEGORY SET IS_DELETED = 1 WHERE PRODUCTS_CATEGORY_NAME = @PRODUCTS_CATEGORY_NAME
		END
		
		IF LOWER(@ACTION) = LOWER(N'ADD_PRODUCTS') AND @PRODUCTS_NAME IS NOT NULL AND @PRODUCTS_CATEGORY_ID IS NOT NULL
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM PRODUCTS WHERE PRODUCTS_NAME = @PRODUCTS_NAME)
			INSERT INTO PRODUCTS (PRODUCTS_NAME, PRODUCTS_CATEGORY_ID, IS_DELETED) VALUES (@PRODUCTS_NAME, @PRODUCTS_CATEGORY_ID, 0)
			ELSE
			UPDATE PRODUCTS SET IS_DELETED = 0 WHERE PRODUCTS_NAME = @PRODUCTS_NAME
		END
		
		IF LOWER(@ACTION) = LOWER(N'MODIFY_PRODUCTS')
		BEGIN
			IF EXISTS(SELECT 1 FROM PRODUCTS WHERE PRODUCTS_NAME = @PRODUCTS_NAME)
			UPDATE PRODUCTS SET PRODUCTS_NAME = ISNULL(@NEW_PRODUCTS_NAME, PRODUCTS_NAME), PRODUCTS_CATEGORY_ID = ISNULL(@PRODUCTS_CATEGORY_ID, PRODUCTS_CATEGORY_ID) WHERE PRODUCTS_NAME = @PRODUCTS_NAME
		END
		
		IF LOWER(@ACTION) = LOWER(N'DELETE_PRODUCTS') AND @PRODUCTS_NAME IS NOT NULL
		BEGIN
			IF EXISTS(SELECT 1 FROM PRODUCTS WHERE PRODUCTS_NAME = @PRODUCTS_NAME)
			UPDATE PRODUCTS SET IS_DELETED = 1 WHERE PRODUCTS_NAME = @PRODUCTS_NAME
		END
		
		SELECT 1;
	END;

CREATE   PROCEDURE MANAGE_INVENTORY_STOCK_REQUEST
    @ACTION NVARCHAR(50),
    @INVENTORY_STOCK_REQUEST_ID NUMERIC(18,0) = NULL,
    @DRIVER_ID NUMERIC(18,0) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    -- MODE 1: Return request details (including lat/long)
    IF LOWER(@ACTION) = LOWER(N'GET_REQUEST_DETAILS')
       AND @INVENTORY_STOCK_REQUEST_ID IS NOT NULL
    BEGIN
        SELECT
            isr.INVENTORY_STOCK_REQUEST_ID,
            il.INVENTORY_LOCATION_NAME        AS REQUESTING_INVENTORY,
            il.INVENTORY_LOCATION_LAT         AS REQUESTING_LAT,
            il.INVENTORY_LOCATION_LONG        AS REQUESTING_LONG,
            il2.INVENTORY_LOCATION_NAME       AS SUPPLYING_INVENTORY,
            il2.INVENTORY_LOCATION_LAT        AS SUPPLYING_LAT,
            il2.INVENTORY_LOCATION_LONG       AS SUPPLYING_LONG,
            p.PRODUCTS_ID,
            p.PRODUCTS_NAME,
            isr.PRODUCTS_COUNT,
            isr.IS_GET,
            CASE WHEN isr.DRIVER_ID_ASSIGNED IS NOT NULL 
                 THEN 1 ELSE 0 
            END AS IS_ACCEPTED_BY_FLEET
        FROM INVENTORY_STOCK_REQUEST isr
        LEFT JOIN PRODUCTS p ON p.PRODUCTS_ID = isr.PRODUCTS_ID
        LEFT JOIN INVENTORY_LOCATION il ON il.INVENTORY_LOCATION_ID = isr.INVENTORY_ID
        LEFT JOIN INVENTORY_LOCATION il2 ON il2.INVENTORY_LOCATION_ID = isr.FROM_INVENTORY_ID
        WHERE isr.INVENTORY_STOCK_REQUEST_ID = @INVENTORY_STOCK_REQUEST_ID
          AND isr.IS_DELETED = 0;
    END

    -- MODE 2: Accept the trip – assign a driver
    IF LOWER(@ACTION) = LOWER(N'ACCEPT_REQUEST')
       AND @INVENTORY_STOCK_REQUEST_ID IS NOT NULL
       AND @DRIVER_ID IS NOT NULL
    BEGIN
        UPDATE INVENTORY_STOCK_REQUEST
        SET DRIVER_ID_ASSIGNED = @DRIVER_ID
        WHERE INVENTORY_STOCK_REQUEST_ID = @INVENTORY_STOCK_REQUEST_ID
          AND IS_DELETED = 0
          AND DRIVER_ID_ASSIGNED IS NULL;

        SELECT 1;
    END
END;

CREATE    PROCEDURE MANAGE_PRODUCTS_MOVEMENT_TRIPS
@ACTION NVARCHAR(50) = NULL,
@PRODUCTS_MOVEMENTS_ID NUMERIC = NULL,
@DRIVERS_ID NUMERIC = NULL,
@VEHICLE_ID NUMERIC = NULL,
@COMES_FROM_LOCATION_ID NUMERIC = NULL,
@GOES_TO_LOCATION_ID NUMERIC = NULL,
@EST_ARIVAL NVARCHAR(19) = NULL,
@DID_ARIVE BIT = NULL,
@PRODUCTS_MOVEMENTS_LIST_ID NUMERIC = NULL,
@PRODUCTS_ID NUMERIC = NULL,
@PRODUCTS_COUNT NUMERIC = NULL
AS
	BEGIN
	
	SET @ACTION = UPPER(@ACTION)

		IF @ACTION = N'DELETE_TRIP'
		AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
		AND (SELECT TOP(1) START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
		BEGIN
			UPDATE PRODUCTS_MOVEMENTS
				SET 
					IS_DELETED = 1,
					IS_ACTIVE = 0
				WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
			
			DELETE FROM MOVEMENTS_PRODUCTS_LIST WHERE MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
		END
		
		IF @ACTION = N'ADD_PRODUCT_TO_TRIP'
		AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL 
        AND @PRODUCTS_ID IS NOT NULL 
        AND @PRODUCTS_COUNT IS NOT NULL
        AND (SELECT TOP(1) START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
			BEGIN
				INSERT INTO MOVEMENTS_PRODUCTS_LIST 
				(
					MOVEMENTS_ID,
					PRODUCTS_ID,
					PRODUCTS_COUNT
				)
				VALUES
				(
					@PRODUCTS_MOVEMENTS_ID,
					@PRODUCTS_ID,
					@PRODUCTS_COUNT
				)
			END
			
		IF @ACTION = N'DELETE_PRODUCT_FROM_TRIP' AND @PRODUCTS_MOVEMENTS_LIST_ID IS NOT NULL
		AND (SELECT TOP(1) START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
			BEGIN
				DELETE FROM MOVEMENTS_PRODUCTS_LIST WHERE MOVEMENTS_PRODUCTS_ID = @PRODUCTS_MOVEMENTS_LIST_ID
			END
			
		IF @ACTION = N'MODIFY_PRODUCT_FROM_TRIP' AND @PRODUCTS_MOVEMENTS_LIST_ID IS NOT NULL
		AND (SELECT TOP(1) START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
			BEGIN
				UPDATE MOVEMENTS_PRODUCTS_LIST
				SET
					PRODUCTS_ID = ISNULL(@PRODUCTS_ID, PRODUCTS_ID),
					PRODUCTS_COUNT = ISNULL(@PRODUCTS_COUNT, PRODUCTS_COUNT) 
				WHERE MOVEMENTS_PRODUCTS_ID = @PRODUCTS_MOVEMENTS_LIST_ID
			END	
		
	
		IF @ACTION = N'ADD_PRODUCTS_TRIP'
        AND @DRIVERS_ID IS NOT NULL
        AND @VEHICLE_ID IS NOT NULL
        AND @COMES_FROM_LOCATION_ID IS NOT NULL
        AND @GOES_TO_LOCATION_ID IS NOT NULL
        AND @COMES_FROM_LOCATION_ID <> @GOES_TO_LOCATION_ID
		BEGIN
			
			INSERT INTO PRODUCTS_MOVEMENTS (
			    DRIVERS_ID,
			    VEHICLE_ID,
			    COMES_FROM_LOCATION_ID,
			    GOES_TO_LOCATION_ID
			)
			VALUES (
			    @DRIVERS_ID,
			    @VEHICLE_ID,
			    @COMES_FROM_LOCATION_ID,
			    @GOES_TO_LOCATION_ID
			)
		END
		
		IF @ACTION = N'MODIFY_TRIP' --THIS IS FOR NOT STARTED TRIPS ONLY
		AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
		AND (SELECT START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
			BEGIN
				
				UPDATE PRODUCTS_MOVEMENTS
					SET 
					    DRIVERS_ID = ISNULL(@DRIVERS_ID, DRIVERS_ID),
					    VEHICLE_ID = ISNULL(@VEHICLE_ID, VEHICLE_ID),
					    COMES_FROM_LOCATION_ID = ISNULL(@COMES_FROM_LOCATION_ID, COMES_FROM_LOCATION_ID),
					    GOES_TO_LOCATION_ID = ISNULL(@GOES_TO_LOCATION_ID, GOES_TO_LOCATION_ID)
					WHERE 
					    PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
				
			END
			
		IF @ACTION = N'START_TRIP' AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
		AND (SELECT START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
			BEGIN
				
				UPDATE PRODUCTS_MOVEMENTS
					SET 
					    START_DATE_HOUR = CONVERT(NVARCHAR(19), GETDATE(), 20),
					    EST_ARIVAL = ISNULL(@EST_ARIVAL, EST_ARIVAL)
					WHERE 
					    PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
			END
			
			
		IF @ACTION = N'END_TRIP' AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
		AND (SELECT END_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
		AND (SELECT START_DATE_HOUR FROM PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NOT NULL
			BEGIN
				UPDATE PRODUCTS_MOVEMENTS
					SET 
					    END_DATE_HOUR = CONVERT(NVARCHAR(19), GETDATE(), 20),
					    DID_ARIVE = ISNULL(@DID_ARIVE, DID_ARIVE),
					    IS_ACTIVE = 0
					WHERE 
					    PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
			END
			
			
		SELECT 1
		
	END;

