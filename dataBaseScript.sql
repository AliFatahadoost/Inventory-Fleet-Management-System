CREATE   PROCEDURE [dbo].[LOGIN_VALID]
@USERNAME NVARCHAR(50),
@PASSWORD NVARCHAR(50)
AS
BEGIN
DECLARE @USER_ID NUMERIC = (SELECT SYS_USER_ID FROM SYS_USERS WHERE LOWER(USERNAME) = LOWER(@USERNAME) AND USER_PASSWORD = HASHBYTES('SHA2_256', CONCAT(N'I%@MBAR#4BI$GI$RL', @PASSWORD, N'4THEYS123#AYIMJO31SEPHSEED')));
	IF @USER_ID IS NOT NULL
	BEGIN
		DECLARE @TOKENVARBINARY VARBINARY(512)
		SET @TOKENVARBINARY = HASHBYTES('SHA2_512', CONCAT(N'I%@MBAR#4BI$GI$RL', @USERNAME, N'4THEYS123#AYIMJO31SEPHSEED', CAST(GETUTCDATE() AS NVARCHAR)))
		
		DECLARE @TOKEN NVARCHAR(512) = CONVERT(NVARCHAR(512), @TOKENVARBINARY, 2);
		
		UPDATE SYS_USERS
		SET
		LOGIN_SESSION = @TOKEN
		WHERE SYS_USER_ID = @USER_ID

		INSERT INTO USER_LOGIN_LOG (SYS_USER_ID, LOGIN_DATE) VALUES (@USER_ID, CONVERT(NVARCHAR(19), GETDATE(), 120))
		
		SELECT 1 AS RESULT, @TOKEN AS TOKEN
	END
	ELSE
	SELECT 0 AS RESULT, N'' AS TOKEN
END;

CREATE   PROCEDURE MANAGE_DRIVERS_AND_TEAMS
    @ACTION NVARCHAR(50),
    @DRIVER_NAME NVARCHAR(50) = NULL,
    @DRIVER_LAST_NAME NVARCHAR(50) = NULL,
    @DRIVERS_NATIONAL_CODE NVARCHAR(50) = NULL,
    @NEW_DRIVER_NAME NVARCHAR(50) = NULL,
    @NEW_DRIVER_LAST_NAME NVARCHAR(50) = NULL,
    @NEW_DRIVERS_NATIONAL_CODE NVARCHAR(50) = NULL,
    @DRIVERS_PHONE_NUMBER NVARCHAR(50) = NULL,
    @NEW_DRIVERS_PHONE_NUMBER NVARCHAR(50) = NULL,
    @FLEET_TEAM_NAME NVARCHAR(50) = NULL,
    @NEW_FLEET_TEAM_NAME NVARCHAR(50) = NULL,
    @DESCRIPTION NVARCHAR(100) = NULL,
    @NEW_DESCRIPTION NVARCHAR(100) = NULL
AS
BEGIN
	DECLARE @FLEET_ID NUMERIC = (SELECT TOP 1 FLEET_TEAM_ID FROM FLEET_TEAMS WHERE LOWER(FLEET_TEAM_NAME) LIKE LOWER(@FLEET_TEAM_NAME))
    -- ========== DRIVERS ==========
    IF LOWER(@ACTION) = LOWER(N'ADD_DRIVER')
       AND @DRIVERS_NATIONAL_CODE IS NOT NULL
       AND @DRIVER_NAME IS NOT NULL
       AND @DRIVER_LAST_NAME IS NOT NULL
       AND @DRIVERS_PHONE_NUMBER IS NOT NULL
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM DRIVERS WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE)
            INSERT INTO DRIVERS (DRIVER_NAME, DRIVER_LAST_NAME, DRIVERS_NATIONAL_CODE, DRIVERS_PHONE_NUMBER, IS_DELETED,FLEET_TEAM_ID)
            VALUES (@DRIVER_NAME, @DRIVER_LAST_NAME, @DRIVERS_NATIONAL_CODE, @DRIVERS_PHONE_NUMBER, 0, @FLEET_ID);
        ELSE
            UPDATE DRIVERS SET IS_DELETED = 0 WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE;
    END

    IF LOWER(@ACTION) = LOWER(N'MODIFY_DRIVER')
       AND @DRIVERS_NATIONAL_CODE IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM DRIVERS WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE)
            UPDATE DRIVERS
            SET DRIVER_NAME = ISNULL(@NEW_DRIVER_NAME, DRIVER_NAME),
                DRIVER_LAST_NAME = ISNULL(@NEW_DRIVER_LAST_NAME, DRIVER_LAST_NAME),
                DRIVERS_NATIONAL_CODE = ISNULL(@NEW_DRIVERS_NATIONAL_CODE, DRIVERS_NATIONAL_CODE),
                DRIVERS_PHONE_NUMBER = ISNULL(@NEW_DRIVERS_PHONE_NUMBER, DRIVERS_PHONE_NUMBER),
                FLEET_TEAM_ID = ISNULL(@FLEET_ID, FLEET_TEAM_ID)
            WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE;
    END

    IF LOWER(@ACTION) = LOWER(N'DELETE_DRIVER')
       AND @DRIVERS_NATIONAL_CODE IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM DRIVERS WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE)
            UPDATE DRIVERS SET IS_DELETED = 1 WHERE DRIVERS_NATIONAL_CODE = @DRIVERS_NATIONAL_CODE;
    END

    -- ========== FLEET TEAMS ==========
    IF LOWER(@ACTION) = LOWER(N'ADD_FLEET_TEAM')
       AND @FLEET_TEAM_NAME IS NOT NULL
       AND @DESCRIPTION IS NOT NULL
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM FLEET_TEAMS WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME)
            INSERT INTO FLEET_TEAMS (FLEET_TEAM_NAME, DESCRIPTION, IS_DELETED)
            VALUES (@FLEET_TEAM_NAME, @DESCRIPTION, 0);
        ELSE
            UPDATE FLEET_TEAMS SET IS_DELETED = 0 WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME;
    END

    IF LOWER(@ACTION) = LOWER(N'MODIFY_FLEET_TEAM')
       AND @FLEET_TEAM_NAME IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM FLEET_TEAMS WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME)
            UPDATE FLEET_TEAMS
            SET FLEET_TEAM_NAME = ISNULL(@NEW_FLEET_TEAM_NAME, FLEET_TEAM_NAME),
                DESCRIPTION = ISNULL(@NEW_DESCRIPTION, DESCRIPTION)
            WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME;
    END

    IF LOWER(@ACTION) = LOWER(N'DELETE_FLEET_TEAM')
       AND @FLEET_TEAM_NAME IS NOT NULL
    BEGIN
        IF EXISTS (SELECT 1 FROM FLEET_TEAMS WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME)
            UPDATE FLEET_TEAMS SET IS_DELETED = 1 WHERE FLEET_TEAM_NAME = @FLEET_TEAM_NAME;
    END

    SELECT 1;
END;

