-- 17. ROLES_MANAGEMENT
CREATE PROCEDURE dbo.ROLES_MANAGEMENT
    @USERNAME NVARCHAR(50),
    @ROLES_TITLE NVARCHAR(50),
    @REVOKE BIT = 0
AS
BEGIN
    DECLARE @SYS_USER_ID NUMERIC = (SELECT TOP 1 SYS_USER_ID FROM dbo.SYS_USERS WHERE LOWER(USERNAME) LIKE LOWER(@USERNAME))
    DECLARE @ROLE_CODE NUMERIC = (SELECT TOP 1 ROLE_CODE FROM dbo.LT_ROLES WHERE LOWER(ROLES_TITLE) LIKE LOWER(@ROLES_TITLE))
    DECLARE @EXISTS BIT = 0;

    IF EXISTS(SELECT 1 FROM dbo.USERS_ROLES WHERE SYS_USER_ID = @SYS_USER_ID AND ROLE_CODE = @ROLE_CODE)
        SET @EXISTS = 1

    IF @SYS_USER_ID IS NOT NULL AND @ROLE_CODE IS NOT NULL
    BEGIN
        IF NOT(@REVOKE = 1)
        BEGIN
            IF @EXISTS = 1
                UPDATE dbo.USERS_ROLES SET IS_ACTIVE = 1 WHERE SYS_USER_ID = @SYS_USER_ID AND ROLE_CODE = @ROLE_CODE
            ELSE
                INSERT INTO dbo.USERS_ROLES (SYS_USER_ID, ROLE_CODE, ASSIGNMENT_DATE, IS_ACTIVE)
                VALUES (@SYS_USER_ID, @ROLE_CODE, CONVERT(NVARCHAR(19), GETDATE(), 120), 1)
        END
        ELSE
        BEGIN
            IF @EXISTS = 1
                UPDATE dbo.USERS_ROLES SET IS_ACTIVE = 0 WHERE SYS_USER_ID = @SYS_USER_ID AND ROLE_CODE = @ROLE_CODE
        END
    END

    SELECT 1 AS STATUS
END
GO

