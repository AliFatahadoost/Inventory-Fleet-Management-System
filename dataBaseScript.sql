CREATE   PROCEDURE HANDLE_INVENTORY_REQUEST
    @ACTION                     NVARCHAR(50),
    @INVENTORY_STOCK_REQUEST_ID NUMERIC = NULL,
    @INVENTORY_ID               NUMERIC = NULL,
    @PRODUCTS_ID                NUMERIC = NULL,
    @PRODUCTS_COUNT             NUMERIC = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET @ACTION = UPPER(@ACTION);

    -- =====================================================================
    --  ACTION: SET_REQUEST
    -- =====================================================================
    IF @ACTION = N'SET_REQUEST'
    BEGIN
        -- Validate required parameters
        IF @INVENTORY_ID IS NULL
            THROW 50001, 'INVENTORY_ID cannot be NULL for SET_REQUEST.', 1;
        IF @PRODUCTS_ID IS NULL
            THROW 50001, 'PRODUCTS_ID cannot be NULL for SET_REQUEST.', 1;
        IF @PRODUCTS_COUNT IS NULL
            THROW 50001, 'PRODUCTS_COUNT cannot be NULL for SET_REQUEST.', 1;

        INSERT INTO INVENTORY_STOCK_REQUEST
        (
            INVENTORY_ID,
            PRODUCTS_ID,
            IS_DELETED,
            DRIVER_ID_ASSIGNED,
            PRODUCTS_COUNT
        )
        VALUES
        (
            @INVENTORY_ID,
            @PRODUCTS_ID,
            0,                  -- IS_DELETED
            NULL,                  -- IS_ACCEPTED_BY_FLEET (default false)
            @PRODUCTS_COUNT     -- PRODUCTS_COUNT (fixed order)
        );
    END

    -- =====================================================================
    --  ACTION: ACCEPT_REQUEST
    -- =====================================================================
    IF @ACTION = N'ACCEPT_REQUEST'
    BEGIN
        -- Validate required parameters
        IF @INVENTORY_STOCK_REQUEST_ID IS NULL
            THROW 50002, 'INVENTORY_STOCK_REQUEST_ID cannot be NULL for ACCEPT_REQUEST.', 1;
        IF @INVENTORY_ID IS NULL
            THROW 50002, 'INVENTORY_ID cannot be NULL for ACCEPT_REQUEST.', 1;
        IF @PRODUCTS_ID IS NULL
            THROW 50002, 'PRODUCTS_ID cannot be NULL for ACCEPT_REQUEST.', 1;

        -- Check that the request exists and is not deleted
        IF NOT EXISTS (
            SELECT 1
            FROM INVENTORY_STOCK_REQUEST
            WHERE INVENTORY_STOCK_REQUEST_ID = @INVENTORY_STOCK_REQUEST_ID
              AND IS_DELETED = 0
        )
            THROW 50003, 'Request not found or has been deleted.', 1;

        -- Ensure source and destination inventories are different
        IF EXISTS (
            SELECT 1
            FROM INVENTORY_STOCK_REQUEST
            WHERE INVENTORY_STOCK_REQUEST_ID = @INVENTORY_STOCK_REQUEST_ID
              AND INVENTORY_ID = @INVENTORY_ID
        )
            THROW 50004, 'Source and destination inventory cannot be the same.', 1;

        -- Perform the update
        UPDATE INVENTORY_STOCK_REQUEST
        SET
            FROM_INVENTORY_ID         = @INVENTORY_ID,
            PRODUCTS_ID             = @PRODUCTS_ID,
            ACCEPT_BY_INVENTORY_ID  = @INVENTORY_ID
        WHERE INVENTORY_STOCK_REQUEST_ID = @INVENTORY_STOCK_REQUEST_ID;
    END
    SELECT 1 AS STATUS
END;

