@END_TASK BIT = NULL
AS
BEGIN
BEGIN TRANSACTION
--DECLARE @TEMP NVARCHAR(MAX)
IF @TASK_ID_ACCPETED IS NOT NULL AND @BY_USER_SESSION IS NOT NULL AND EXISTS(SELECT 1 FROM TASKS WHERE TASKS_ID = @TASK_ID_ACCPETED) AND NOT @END_TASK = 1
BEGIN
