CREATE   PROCEDURE [dbo].[WORK_HOUR_REPORT]
@LOGIN_SESSION NVARCHAR(512)
AS 
BEGIN
SELECT
WHRL.WORK_HOUR_REPORT_LOG_ID, 
SU.USERNAME,
TASK_NAME,
TASK_DESCRIPTION,
START_DATE_TIME,
END_DATE_TIME,
EST_HOURS_IT_WILL_TAKE,
ACTUAL_TIME_TASK_TOOK,
HOURLY_RATE_FOR_TASK,
CAST((HOURLY_RATE_FOR_TASK * ACTUAL_TIME_TASK_TOOK)AS money) AS MONEY_MADE,
SU.BASE_SALARY
FROM
WORK_HOUR_REPORT_LOG WHRL
INNER JOIN SYS_USERS SU
ON WHRL.SYS_USER_ID = SU.SYS_USER_ID
INNER JOIN TASKS T
ON T.TASKS_ID = WHRL.COMPLETED_TASK_ID
WHERE SU.LOGIN_SESSION = @LOGIN_SESSION AND END_DATE_TIME IS NOT NULL
ORDER BY END_DATE_TIME DESC
END
