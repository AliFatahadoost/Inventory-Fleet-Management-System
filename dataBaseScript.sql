CREATE   PROCEDURE [dbo].[CREATE_UPDATE_DELETE_ROLES]
@ACTION_NAME NVARCHAR(20),
@ROLE_CODE NUMERIC = 0,
@ROLE_NAME NVARCHAR(50) = NULL,
@SYS_OBJECT_NAME NVARCHAR(50) = NULL,
@CAN_READ BIT = 0,
@CAN_WRITE BIT = 0
AS
BEGIN
DECLARE @OBJECT_CODE NUMERIC = (SELECT TOP 1 SYS_OBJECT_CODE FROM SYS_OBJECTS WHERE SYS_OBJECT_NAME = @SYS_OBJECT_NAME)
	IF LOWER(@ACTION_NAME) = LOWER(N'DELETE_ROLE') AND NOT @ROLE_CODE = 0
		BEGIN
			DELETE FROM SYS_CALL_ACCESS WHERE ROLE_CODE = @ROLE_CODE
			DELETE FROM LT_ROLES WHERE ROLE_CODE = @ROLE_CODE
		END
	ELSE IF LOWER(@ACTION_NAME) = LOWER(N'CREATE_ROLE') AND @ROLE_NAME IS NOT NULL
			AND NOT EXISTS(SELECT 1 FROM LT_ROLES WHERE ROLE_CODE = @ROLE_CODE)
		BEGIN
			INSERT INTO LT_ROLES (ROLE_CODE, ROLES_TITLE) VALUES (@ROLE_CODE, @ROLE_NAME)
		END
	ELSE IF LOWER(@ACTION_NAME) = LOWER(N'UPDATE_ROLE') AND NOT @ROLE_CODE = 0
		BEGIN
			UPDATE LT_ROLES SET ROLES_TITLE = @ROLE_NAME WHERE ROLE_CODE = @ROLE_CODE
		END
	ELSE IF LOWER(@ACTION_NAME) = LOWER(N'ADD_PERMISSION') AND NOT @ROLE_CODE = 0 AND @SYS_OBJECT_NAME IS NOT NULL
			AND EXISTS(SELECT TOP 1 1 FROM SYS_OBJECTS WHERE SYS_OBJECT_NAME = @SYS_OBJECT_NAME)
			AND EXISTS(SELECT TOP 1 1 FROM LT_ROLES WHERE ROLE_CODE = @ROLE_CODE)
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM SYS_CALL_ACCESS WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE)
				BEGIN
					INSERT INTO SYS_CALL_ACCESS (ROLE_CODE, SYS_OBJECT_CODE, CAN_READ, CAN_WRITE) VALUES (@ROLE_CODE, @OBJECT_CODE, @CAN_READ, @CAN_WRITE)
				END
			ELSE
				BEGIN
					UPDATE SYS_CALL_ACCESS
					SET
						CAN_READ = @CAN_READ,
						CAN_WRITE = @CAN_WRITE
						WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE
				END
		END
	ELSE IF LOWER(@ACTION_NAME) = LOWER(N'DELETE_PERMISSION') AND NOT @ROLE_CODE = 0 AND @SYS_OBJECT_NAME IS NOT NULL
		BEGIN
			DELETE FROM SYS_CALL_ACCESS WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE
		END

	SELECT 1 AS STATUS
END;

CREATE   PROCEDURE CREATE_UPDATE_DELETE_TASK
    @ACTION                NVARCHAR(50),
    @USER_ID               NUMERIC        = NULL,
    @TASK_ID               NUMERIC        = NULL,
    @TASK_NAME             NVARCHAR(50)   = NULL,
    @TASK_DESC             NVARCHAR(100)  = NULL,
    @TASK_FOR_ROLE_ID      NUMERIC        = NULL,
    @EST_HOURS_IT_TAKES    DECIMAL(6,2)   = NULL,
    @HOURLY_PAYMENT_RATE   DECIMAL(6,2)   = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET @ACTION = UPPER(@ACTION);

    -- =========================================================
    -- CREATE or RESTORE a task (soft‑delete reversal)
    -- =========================================================
    IF @ACTION = N'CREATE_TASK'
       AND @TASK_NAME IS NOT NULL
       AND @TASK_DESC IS NOT NULL
       AND @TASK_FOR_ROLE_ID IS NOT NULL
       AND @EST_HOURS_IT_TAKES IS NOT NULL
       AND @HOURLY_PAYMENT_RATE IS NOT NULL
       AND @USER_ID IS NOT NULL
    BEGIN
        -- Uniqueness check on (NAME, DESCRIPTION, ROLE)
        IF NOT EXISTS (
            SELECT 1 FROM PROJECT_ZERO.dbo.TASKS
            WHERE TASK_NAME        = @TASK_NAME
              AND TASK_DESCRIPTION = @TASK_DESC
              AND TASK_FOR_ROLE_ID = @TASK_FOR_ROLE_ID
        )
            INSERT INTO PROJECT_ZERO.dbo.TASKS
            (
                TASK_NAME,
                TASK_DESCRIPTION,
                TASK_FOR_ROLE_ID,
                EST_HOURS_IT_WILL_TAKE,
                HOURLY_RATE_FOR_TASK,
                TASK_CREATED_BY_SYS_USER_ID,
                CREATED_DATE
            )
            VALUES
            (
                @TASK_NAME,
                @TASK_DESC,
                @TASK_FOR_ROLE_ID,
                @EST_HOURS_IT_TAKES,
                @HOURLY_PAYMENT_RATE,
                @USER_ID,
                CONVERT(NVARCHAR(19), GETDATE(), 120)
            );
        ELSE
            -- Restore the existing (soft‑deleted) record and refresh its data
            UPDATE PROJECT_ZERO.dbo.TASKS
            SET
                IS_DELETED              = 0,
                TASK_NAME               = @TASK_NAME,
                TASK_DESCRIPTION        = @TASK_DESC,
                TASK_FOR_ROLE_ID        = @TASK_FOR_ROLE_ID,
                EST_HOURS_IT_WILL_TAKE  = @EST_HOURS_IT_TAKES,
                HOURLY_RATE_FOR_TASK    = @HOURLY_PAYMENT_RATE
            WHERE TASK_NAME        = @TASK_NAME
              AND TASK_DESCRIPTION = @TASK_DESC
              AND TASK_FOR_ROLE_ID = @TASK_FOR_ROLE_ID;
    END

    -- =========================================================
    -- UPDATE an existing task by ID
    -- =========================================================
    IF @ACTION = N'UPDATE_TASK'
       AND @TASK_ID IS NOT NULL
    BEGIN
        IF EXISTS (
            SELECT 1 FROM PROJECT_ZERO.dbo.TASKS
            WHERE TASKS_ID = @TASK_ID
        )
            UPDATE PROJECT_ZERO.dbo.TASKS
            SET
                TASK_NAME               = ISNULL(@TASK_NAME,            TASK_NAME),
                TASK_DESCRIPTION        = ISNULL(@TASK_DESC,            TASK_DESCRIPTION),
                TASK_FOR_ROLE_ID        = ISNULL(@TASK_FOR_ROLE_ID,     TASK_FOR_ROLE_ID),
                EST_HOURS_IT_WILL_TAKE  = ISNULL(@EST_HOURS_IT_TAKES,   EST_HOURS_IT_WILL_TAKE),
                HOURLY_RATE_FOR_TASK    = ISNULL(@HOURLY_PAYMENT_RATE,  HOURLY_RATE_FOR_TASK)
            WHERE TASKS_ID = @TASK_ID;
    END

    -- =========================================================
    -- SOFT DELETE a task by ID (sets IS_DELETED = 1)
    -- =========================================================
    IF @ACTION = N'DELETE_TASK'
       AND @TASK_ID IS NOT NULL
    BEGIN
        IF EXISTS (
            SELECT 1 FROM PROJECT_ZERO.dbo.TASKS
            WHERE TASKS_ID = @TASK_ID
        )
            UPDATE PROJECT_ZERO.dbo.TASKS
            SET IS_DELETED = 1
            WHERE TASKS_ID = @TASK_ID;
    END

    SELECT 1 AS STATUS;
END;

