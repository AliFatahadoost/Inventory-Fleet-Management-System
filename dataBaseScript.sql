CREATE   PROCEDURE USP_CREATE_MOVEMENT_FROM_STOCK_REQUEST
    @RequestIDs NVARCHAR(MAX),      -- e.g. '1|2|3'
    @VehicleID  NUMERIC(18,0)       -- vehicle to assign to the movement
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        -- 1. Split the pipe-separated IDs into a table
        DECLARE @ParsedIDs TABLE (ID NUMERIC(18,0));
        INSERT INTO @ParsedIDs (ID)
        SELECT CAST(value AS NUMERIC(18,0))
        FROM STRING_SPLIT(@RequestIDs, '|')
        WHERE RTRIM(value) <> '';

        IF NOT EXISTS (SELECT 1 FROM @ParsedIDs)
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END

        -- 2. Check that every ID exists and is NOT already deleted
        IF EXISTS (
            SELECT 1
            FROM @ParsedIDs p
            LEFT JOIN INVENTORY_STOCK_REQUEST r
                ON p.ID = r.INVENTORY_STOCK_REQUEST_ID
                AND r.IS_DELETED = 0
            WHERE r.INVENTORY_STOCK_REQUEST_ID IS NULL
        )
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END

        -- 3. Verify same driver and same origin
        DECLARE @DriverID NUMERIC(18,0),
                @FromLoc  NUMERIC(18,0),
                @ToLoc    NUMERIC(18,0),
                @MaxDriver NUMERIC(18,0),
                @MaxFrom   NUMERIC(18,0);

        SELECT @DriverID   = MIN(DRIVER_ID_ASSIGNED),
               @FromLoc    = MIN(FROM_INVENTORY_ID),
               @ToLoc      = MIN(INVENTORY_ID),
               @MaxDriver  = MAX(DRIVER_ID_ASSIGNED),
               @MaxFrom    = MAX(FROM_INVENTORY_ID)
        FROM INVENTORY_STOCK_REQUEST
        WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
          AND IS_DELETED = 0;

        IF @DriverID IS NULL OR @DriverID != @MaxDriver
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END
        IF @FromLoc IS NULL OR @FromLoc != @MaxFrom
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END

        -- 4. All destinations must be non-NULL
        IF EXISTS (
            SELECT 1 FROM INVENTORY_STOCK_REQUEST
            WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
              AND IS_DELETED = 0
              AND INVENTORY_ID IS NULL
        )
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END

        DECLARE @StartDate NVARCHAR(19) = CONVERT(NVARCHAR(19), GETDATE(), 120);

        -- 5. Build pipe-separated list of all distinct destinations for the NVARCHAR column
        DECLARE @AllDestinations NVARCHAR(MAX) = '';
        
        SELECT @AllDestinations = STRING_AGG(CAST(INVENTORY_ID AS NVARCHAR(20)), '|')
        FROM (
            SELECT DISTINCT INVENTORY_ID
            FROM INVENTORY_STOCK_REQUEST
            WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
              AND IS_DELETED = 0
        ) AS Destinations;

        -- 6. Aggregate ALL products
        DECLARE @AggregatedProducts TABLE (
            PRODUCTS_ID NUMERIC(18,0),
            PRODUCTS_COUNT NUMERIC(18,0)
        );

        INSERT INTO @AggregatedProducts (PRODUCTS_ID, PRODUCTS_COUNT)
        SELECT r.PRODUCTS_ID,
               SUM(r.PRODUCTS_COUNT)
        FROM INVENTORY_STOCK_REQUEST r
        WHERE r.INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
          AND r.IS_DELETED = 0
          AND r.PRODUCTS_COUNT > 0
        GROUP BY r.PRODUCTS_ID;

        -- 7. DUPLICATE CHECK
        IF EXISTS (
            SELECT 1
            FROM PRODUCTS_MOVEMENTS pm
            WHERE pm.DRIVERS_ID           = @DriverID
              AND pm.VEHICLE_ID           = @VehicleID
              AND pm.COMES_FROM_LOCATION_ID = @FromLoc
              AND pm.GOES_TO_LOCATION_ID   = @ToLoc
              AND pm.START_DATE_HOUR      = @StartDate
              AND pm.IS_DELETED           = 0
              AND NOT EXISTS (
                  SELECT mpl.PRODUCTS_ID, mpl.PRODUCTS_COUNT
                  FROM MOVEMENTS_PRODUCTS_LIST mpl
                  WHERE mpl.MOVEMENTS_ID = pm.PRODUCTS_MOVEMENTS_ID
                  EXCEPT
                  SELECT PRODUCTS_ID, PRODUCTS_COUNT FROM @AggregatedProducts
              )
              AND NOT EXISTS (
                  SELECT PRODUCTS_ID, PRODUCTS_COUNT FROM @AggregatedProducts
                  EXCEPT
                  SELECT mpl.PRODUCTS_ID, mpl.PRODUCTS_COUNT
                  FROM MOVEMENTS_PRODUCTS_LIST mpl
                  WHERE mpl.MOVEMENTS_ID = pm.PRODUCTS_MOVEMENTS_ID
              )
        )
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
            RETURN;
        END

        -- 8. Create ONE movement
        INSERT INTO PRODUCTS_MOVEMENTS
            (DRIVERS_ID, VEHICLE_ID, COMES_FROM_LOCATION_ID, GOES_TO_LOCATION_ID,
             GOES_TO_LOCATION_ID_l, START_DATE_HOUR, END_DATE_HOUR, EST_ARIVAL, DID_ARIVE, IS_DELETED, IS_ACTIVE)
        VALUES
            (@DriverID, @VehicleID, @FromLoc, @ToLoc,
             @AllDestinations, @StartDate, NULL, NULL, 0, 0, 1);

        DECLARE @NewMovementID NUMERIC(18,0) = SCOPE_IDENTITY();

        -- 9. Insert aggregated products
        INSERT INTO MOVEMENTS_PRODUCTS_LIST
            (MOVEMENTS_ID, PRODUCTS_ID, PRODUCTS_COUNT)
        SELECT @NewMovementID, PRODUCTS_ID, PRODUCTS_COUNT
        FROM @AggregatedProducts;

        -- 10. Mark stock requests as deleted
        UPDATE INVENTORY_STOCK_REQUEST
        SET IS_DELETED = 1
        WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
          AND IS_DELETED = 0;

        -- 11. Return success
        COMMIT TRANSACTION;
        SELECT (SELECT 1 AS Status, @NewMovementID AS MovementID FOR JSON PATH) AS Result;

    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        SELECT (SELECT 0 AS Status, 0 AS MovementID FOR JSON PATH) AS Result;
    END CATCH
END;

CREATE   PROCEDURE usp_CreateMovementFromStockRequests
    @RequestIDs NVARCHAR(MAX),      -- e.g. '1,2,3'
    @VehicleID  NUMERIC(18,0)       -- vehicle to assign to the movement
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        -- 1. Split the comma-separated IDs into a table
        DECLARE @ParsedIDs TABLE (ID NUMERIC(18,0));
        INSERT INTO @ParsedIDs (ID)
        SELECT CAST(value AS NUMERIC(18,0))
        FROM STRING_SPLIT(@RequestIDs, ',')
        WHERE RTRIM(value) <> '';

        -- 2. If nothing was passed, return 0
        IF NOT EXISTS (SELECT 1 FROM @ParsedIDs)
        BEGIN
            SELECT 0 AS Status;
            ROLLBACK TRANSACTION;
            RETURN;
        END

        -- 3. Check that every ID exists in INVENTORY_STOCK_REQUEST
        IF EXISTS (
            SELECT 1
            FROM @ParsedIDs p
            LEFT JOIN INVENTORY_STOCK_REQUEST r
                ON p.ID = r.INVENTORY_STOCK_REQUEST_ID
            WHERE r.INVENTORY_STOCK_REQUEST_ID IS NULL
        )
        BEGIN
            SELECT 0 AS Status;
            ROLLBACK TRANSACTION;
            RETURN;
        END

        -- 4. Verify same driver and same origin (DESTINATION NOT ENFORCED)
        DECLARE @DriverID NUMERIC(18,0),
                @FromLoc  NUMERIC(18,0),
                @ToLoc    NUMERIC(18,0),
                @MaxDriver NUMERIC(18,0),
                @MaxFrom   NUMERIC(18,0);

        SELECT @DriverID   = MIN(DRIVER_ID_ASSIGNED),
               @FromLoc    = MIN(FROM_INVENTORY_ID),
               @ToLoc      = MIN(INVENTORY_ID),        -- will be used as GOES_TO_LOCATION_ID
               @MaxDriver  = MAX(DRIVER_ID_ASSIGNED),
               @MaxFrom    = MAX(FROM_INVENTORY_ID)
        FROM INVENTORY_STOCK_REQUEST
        WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs);

        IF @DriverID IS NULL OR @DriverID != @MaxDriver
        BEGIN
            SELECT 0 AS Status;
            ROLLBACK TRANSACTION;
            RETURN;
        END
        IF @FromLoc IS NULL OR @FromLoc != @MaxFrom
        BEGIN
            SELECT 0 AS Status;
            ROLLBACK TRANSACTION;
            RETURN;
        END
        -- (No check on destination – any mix is allowed)

        -- 5. Create the movement
        DECLARE @StartDate NVARCHAR(19) = CONVERT(NVARCHAR(19), GETDATE(), 120);

        INSERT INTO PRODUCTS_MOVEMENTS
            (DRIVERS_ID, VEHICLE_ID, COMES_FROM_LOCATION_ID, GOES_TO_LOCATION_ID,
             START_DATE_HOUR, END_DATE_HOUR, EST_ARIVAL, DID_ARIVE, IS_DELETED, IS_ACTIVE)
        VALUES
            (@DriverID, @VehicleID, @FromLoc, @ToLoc,
             @StartDate, NULL, NULL, 0, 0, 1);

        DECLARE @NewMovementID NUMERIC(18,0) = SCOPE_IDENTITY();

        -- 6. Insert aggregated products into MOVEMENTS_PRODUCTS_LIST
        INSERT INTO MOVEMENTS_PRODUCTS_LIST
            (MOVEMENTS_ID, PRODUCTS_ID, PRODUCTS_COUNT)
        SELECT
            @NewMovementID,
            r.PRODUCTS_ID,
            SUM(r.PRODUCTS_COUNT)
        FROM INVENTORY_STOCK_REQUEST r
        WHERE r.INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs)
          AND r.PRODUCTS_COUNT > 0
        GROUP BY r.PRODUCTS_ID;

        -- 7. Mark the processed stock requests as deleted
        UPDATE INVENTORY_STOCK_REQUEST
        SET IS_DELETED = 1
        WHERE INVENTORY_STOCK_REQUEST_ID IN (SELECT ID FROM @ParsedIDs);

        -- 8. Success – return the new movement ID
        SELECT 1 AS Status;
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        -- On any error, return 0
        SELECT 0 AS Status;
    END CATCH
END;

CREATE   PROCEDURE [dbo].[WORK_HOUR_REPORT]
@LOGIN_SESSION NVARCHAR(512)
AS 
BEGIN
SELECT
WHRL.WORK_HOUR_REPORT_LOG_ID, 
SU.USERNAME,
TASK_NAME,
TASK_DESCRIPTION,
START_DATE_TIME,
END_DATE_TIME,
EST_HOURS_IT_WILL_TAKE,
ACTUAL_TIME_TASK_TOOK,
HOURLY_RATE_FOR_TASK,
CAST((HOURLY_RATE_FOR_TASK * ACTUAL_TIME_TASK_TOOK)AS money) AS MONEY_MADE,
SU.BASE_SALARY
FROM
WORK_HOUR_REPORT_LOG WHRL
INNER JOIN SYS_USERS SU
ON WHRL.SYS_USER_ID = SU.SYS_USER_ID
INNER JOIN TASKS T
ON T.TASKS_ID = WHRL.COMPLETED_TASK_ID
WHERE SU.LOGIN_SESSION = @LOGIN_SESSION AND END_DATE_TIME IS NOT NULL
ORDER BY END_DATE_TIME DESC
END;