-- 1. ACTIVITY_LOG_MANAGER (called by several others)
CREATE PROCEDURE dbo.ACTIVITY_LOG_MANAGER
    @READ_ONLY BIT = 1,
    @LOGGIN_SESSION NVARCHAR(512) = NULL,
    @ACTIVITY_REMARK NVARCHAR(300) = NULL
AS
BEGIN
    DECLARE @SYS_USER_ID NUMERIC = (SELECT TOP 1 SYS_USER_ID FROM dbo.SYS_USERS WHERE LOGIN_SESSION = @LOGGIN_SESSION)

    IF @READ_ONLY = 0
    BEGIN
        INSERT INTO dbo.ACTIVITY_LOG (SYS_USER_ID, ACTIVITY_REMARKS, DATE_TIME)
        VALUES (@SYS_USER_ID, @ACTIVITY_REMARK, CONVERT(NVARCHAR(19), GETDATE(), 120))
        SELECT 1 AS STATUS
    END
    ELSE
    BEGIN
        SELECT ACTIVITY_LOG_ID, AL.SYS_USER_ID, USERNAME, AL.ACTIVITY_REMARKS, DATE_TIME
        FROM dbo.ACTIVITY_LOG AL
        INNER JOIN dbo.SYS_USERS SU ON AL.SYS_USER_ID = SU.SYS_USER_ID
    END
END
GO

-- 2. CHANGE_PASSWORD
CREATE PROCEDURE dbo.CHANGE_PASSWORD
    @NEW_PASSWORD NVARCHAR(50),
    @OLD_PASSWORD NVARCHAR(50),
    @LOGIN_SESSION NVARCHAR(512)
AS
BEGIN
    IF EXISTS(SELECT 1 FROM dbo.SYS_USERS WHERE LOGIN_SESSION = @LOGIN_SESSION
              AND USER_PASSWORD = HASHBYTES('SHA2_256', CONCAT(N'I%@MBAR#4BI$GI$RL', @OLD_PASSWORD, N'4THEYS123#AYIMJO31SEPHSEED')))
    BEGIN
        UPDATE dbo.SYS_USERS
        SET USER_PASSWORD = HASHBYTES('SHA2_256', CONCAT(N'I%@MBAR#4BI$GI$RL', @NEW_PASSWORD, N'4THEYS123#AYIMJO31SEPHSEED'))
        WHERE LOGIN_SESSION = @LOGIN_SESSION
        SELECT 1 AS STATUS
        EXEC dbo.ACTIVITY_LOG_MANAGER 0, @LOGIN_SESSION, N'USER SUCCESSFULLY CHANGED PASSWORD'
    END
    ELSE
    BEGIN
        SELECT 0 AS STATUS
        EXEC dbo.ACTIVITY_LOG_MANAGER 0, @LOGIN_SESSION, N'USER TRIED AND FAILED TO CHANGE PASSWORD'
    END
END
GO

