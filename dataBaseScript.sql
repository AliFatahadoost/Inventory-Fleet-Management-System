-- 7. CREATE_UPDATE_DELETE_ROLES
CREATE PROCEDURE dbo.CREATE_UPDATE_DELETE_ROLES
    @ACTION_NAME NVARCHAR(20),
    @ROLE_CODE NUMERIC = 0,
    @ROLE_NAME NVARCHAR(50) = NULL,
    @SYS_OBJECT_NAME NVARCHAR(50) = NULL,
    @CAN_READ BIT = 0,
    @CAN_WRITE BIT = 0
AS
BEGIN
    DECLARE @OBJECT_CODE NUMERIC = (SELECT TOP 1 SYS_OBJECT_CODE FROM dbo.SYS_OBJECTS WHERE SYS_OBJECT_NAME = @SYS_OBJECT_NAME)
    IF LOWER(@ACTION_NAME) = LOWER(N'DELETE_ROLE') AND NOT @ROLE_CODE = 0
    BEGIN
        DELETE FROM dbo.SYS_CALL_ACCESS WHERE ROLE_CODE = @ROLE_CODE
        DELETE FROM dbo.LT_ROLES WHERE ROLE_CODE = @ROLE_CODE
    END
    ELSE IF LOWER(@ACTION_NAME) = LOWER(N'CREATE_ROLE') AND @ROLE_NAME IS NOT NULL
            AND NOT EXISTS(SELECT 1 FROM dbo.LT_ROLES WHERE ROLE_CODE = @ROLE_CODE)
    BEGIN
        INSERT INTO dbo.LT_ROLES (ROLE_CODE, ROLES_TITLE) VALUES (@ROLE_CODE, @ROLE_NAME)
    END
    ELSE IF LOWER(@ACTION_NAME) = LOWER(N'UPDATE_ROLE') AND NOT @ROLE_CODE = 0
    BEGIN
        UPDATE dbo.LT_ROLES SET ROLES_TITLE = @ROLE_NAME WHERE ROLE_CODE = @ROLE_CODE
    END
    ELSE IF LOWER(@ACTION_NAME) = LOWER(N'ADD_PERMISSION') AND NOT @ROLE_CODE = 0 AND @SYS_OBJECT_NAME IS NOT NULL
            AND EXISTS(SELECT TOP 1 1 FROM dbo.SYS_OBJECTS WHERE SYS_OBJECT_NAME = @SYS_OBJECT_NAME)
            AND EXISTS(SELECT TOP 1 1 FROM dbo.LT_ROLES WHERE ROLE_CODE = @ROLE_CODE)
    BEGIN
        IF NOT EXISTS(SELECT 1 FROM dbo.SYS_CALL_ACCESS WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE)
            INSERT INTO dbo.SYS_CALL_ACCESS (ROLE_CODE, SYS_OBJECT_CODE, CAN_READ, CAN_WRITE)
            VALUES (@ROLE_CODE, @OBJECT_CODE, @CAN_READ, @CAN_WRITE)
        ELSE
            UPDATE dbo.SYS_CALL_ACCESS
            SET CAN_READ = @CAN_READ,
                CAN_WRITE = @CAN_WRITE
            WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE
    END
    ELSE IF LOWER(@ACTION_NAME) = LOWER(N'DELETE_PERMISSION') AND NOT @ROLE_CODE = 0 AND @SYS_OBJECT_NAME IS NOT NULL
    BEGIN
        DELETE FROM dbo.SYS_CALL_ACCESS WHERE SYS_OBJECT_CODE = @OBJECT_CODE AND ROLE_CODE = @ROLE_CODE
    END

    SELECT 1 AS STATUS
END
GO

