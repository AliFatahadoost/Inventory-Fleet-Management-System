-- 16. MANAGE_PRODUCTS_MOVEMENT_TRIPS
CREATE PROCEDURE dbo.MANAGE_PRODUCTS_MOVEMENT_TRIPS
    @ACTION NVARCHAR(50) = NULL,
    @PRODUCTS_MOVEMENTS_ID NUMERIC = NULL,
    @DRIVERS_ID NUMERIC = NULL,
    @VEHICLE_ID NUMERIC = NULL,
    @COMES_FROM_LOCATION_ID NUMERIC = NULL,
    @GOES_TO_LOCATION_ID NUMERIC = NULL,
    @EST_ARIVAL NVARCHAR(19) = NULL,
    @DID_ARIVE BIT = NULL,
    @PRODUCTS_MOVEMENTS_LIST_ID NUMERIC = NULL,
    @PRODUCTS_ID NUMERIC = NULL,
    @PRODUCTS_COUNT NUMERIC = NULL
AS
BEGIN
    SET @ACTION = UPPER(@ACTION)

    IF @ACTION = N'DELETE_TRIP'
       AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
       AND (SELECT TOP(1) START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        UPDATE dbo.PRODUCTS_MOVEMENTS
        SET IS_DELETED = 1,
            IS_ACTIVE = 0
        WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID

        DELETE FROM dbo.MOVEMENTS_PRODUCTS_LIST WHERE MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
    END

    IF @ACTION = N'ADD_PRODUCT_TO_TRIP'
       AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
       AND @PRODUCTS_ID IS NOT NULL
       AND @PRODUCTS_COUNT IS NOT NULL
       AND (SELECT TOP(1) START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        INSERT INTO dbo.MOVEMENTS_PRODUCTS_LIST (MOVEMENTS_ID, PRODUCTS_ID, PRODUCTS_COUNT)
        VALUES (@PRODUCTS_MOVEMENTS_ID, @PRODUCTS_ID, @PRODUCTS_COUNT)
    END

    IF @ACTION = N'DELETE_PRODUCT_FROM_TRIP' AND @PRODUCTS_MOVEMENTS_LIST_ID IS NOT NULL
       AND (SELECT TOP(1) START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        DELETE FROM dbo.MOVEMENTS_PRODUCTS_LIST WHERE MOVEMENTS_PRODUCTS_ID = @PRODUCTS_MOVEMENTS_LIST_ID
    END

    IF @ACTION = N'MODIFY_PRODUCT_FROM_TRIP' AND @PRODUCTS_MOVEMENTS_LIST_ID IS NOT NULL
       AND (SELECT TOP(1) START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        UPDATE dbo.MOVEMENTS_PRODUCTS_LIST
        SET PRODUCTS_ID = ISNULL(@PRODUCTS_ID, PRODUCTS_ID),
            PRODUCTS_COUNT = ISNULL(@PRODUCTS_COUNT, PRODUCTS_COUNT)
        WHERE MOVEMENTS_PRODUCTS_ID = @PRODUCTS_MOVEMENTS_LIST_ID
    END

    IF @ACTION = N'ADD_PRODUCTS_TRIP'
       AND @DRIVERS_ID IS NOT NULL
       AND @VEHICLE_ID IS NOT NULL
       AND @COMES_FROM_LOCATION_ID IS NOT NULL
       AND @GOES_TO_LOCATION_ID IS NOT NULL
       AND @COMES_FROM_LOCATION_ID <> @GOES_TO_LOCATION_ID
    BEGIN
        INSERT INTO dbo.PRODUCTS_MOVEMENTS (DRIVERS_ID, VEHICLE_ID, COMES_FROM_LOCATION_ID, GOES_TO_LOCATION_ID)
        VALUES (@DRIVERS_ID, @VEHICLE_ID, @COMES_FROM_LOCATION_ID, @GOES_TO_LOCATION_ID)
    END

    IF @ACTION = N'MODIFY_TRIP'
       AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
       AND (SELECT START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        UPDATE dbo.PRODUCTS_MOVEMENTS
        SET DRIVERS_ID = ISNULL(@DRIVERS_ID, DRIVERS_ID),
            VEHICLE_ID = ISNULL(@VEHICLE_ID, VEHICLE_ID),
            COMES_FROM_LOCATION_ID = ISNULL(@COMES_FROM_LOCATION_ID, COMES_FROM_LOCATION_ID),
            GOES_TO_LOCATION_ID = ISNULL(@GOES_TO_LOCATION_ID, GOES_TO_LOCATION_ID)
        WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
    END

    IF @ACTION = N'START_TRIP' AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
       AND (SELECT START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
    BEGIN
        UPDATE dbo.PRODUCTS_MOVEMENTS
        SET START_DATE_HOUR = CONVERT(NVARCHAR(19), GETDATE(), 20),
            EST_ARIVAL = ISNULL(@EST_ARIVAL, EST_ARIVAL)
        WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
    END

    IF @ACTION = N'END_TRIP' AND @PRODUCTS_MOVEMENTS_ID IS NOT NULL
       AND (SELECT END_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NULL
       AND (SELECT START_DATE_HOUR FROM dbo.PRODUCTS_MOVEMENTS WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID) IS NOT NULL
    BEGIN
        UPDATE dbo.PRODUCTS_MOVEMENTS
        SET END_DATE_HOUR = CONVERT(NVARCHAR(19), GETDATE(), 20),
            DID_ARIVE = ISNULL(@DID_ARIVE, DID_ARIVE),
            IS_ACTIVE = 0
        WHERE PRODUCTS_MOVEMENTS_ID = @PRODUCTS_MOVEMENTS_ID
    END

    SELECT 1
END
