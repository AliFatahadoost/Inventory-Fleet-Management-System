CREATE   PROCEDURE [dbo].[ACTIVITY_LOG_MANAGER]
@READ_ONLY BIT = 1
,@LOGGIN_SESSION NVARCHAR(512) = NULL
,@ACTIVITY_REMARK NVARCHAR(300) = NULL
AS
BEGIN

	DECLARE @SYS_USER_ID NUMERIC = (SELECT TOP 1 SYS_USER_ID FROM SYS_USERS WHERE LOGIN_SESSION = @LOGGIN_SESSION)

